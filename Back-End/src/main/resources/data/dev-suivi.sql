DROP SCHEMA IF EXISTS public CASCADE;

CREATE SCHEMA public;

CREATE TABLE Users(
   id_user BIGINT GENERATED BY DEFAULT AS IDENTITY,
   first_name VARCHAR(50),
   last_name VARCHAR(50),
   email VARCHAR(50) NOT NULL,
   password VARCHAR(255) NOT NULL,
   roles text[] NOT NULL,
   PRIMARY KEY(id_user)
);

CREATE TABLE Server(
   id_server BIGINT GENERATED BY DEFAULT AS IDENTITY,
   name VARCHAR(50) NOT NULL,
   description TEXT,
   PRIMARY KEY(id_server)
);

CREATE TABLE Project(
   id_project BIGINT GENERATED BY DEFAULT AS IDENTITY,
   name VARCHAR(50) NOT NULL,
   description TEXT,
   quota INT,
   status VARCHAR(50),
   id_server BIGINT NOT NULL,
   PRIMARY KEY(id_project),
   FOREIGN KEY(id_server) REFERENCES Server(id_server)
);

CREATE TABLE Contribution(
   id_contribution BIGINT GENERATED BY DEFAULT AS IDENTITY,
   duration INT NOT NULL,
   date_contribution DATE NOT NULL,
   id_project BIGINT NOT NULL,
   id_user BIGINT NOT NULL,
   PRIMARY KEY(id_contribution),
   FOREIGN KEY(id_project) REFERENCES Project(id_project),
   FOREIGN KEY(id_user) REFERENCES Users(id_user)
);

CREATE TABLE Assign(
   id_user BIGINT,
   id_project BIGINT,
   PRIMARY KEY(id_user, id_project),
   FOREIGN KEY(id_user) REFERENCES Users(id_user),
   FOREIGN KEY(id_project) REFERENCES Project(id_project)
);